fun stringsForLanguage(language: AppLanguage, systemLanguageCode: String = Locale.getDefault().language): AppStrings {
    val effectiveCode = when (language) {
        AppLanguage.SYSTEM -> systemLanguageCode.lowercase(Locale.ROOT)
        AppLanguage.GERMAN -> "de"
        AppLanguage.ENGLISH -> "en"
        AppLanguage.SPANISH -> "es"
        AppLanguage.FRENCH -> "fr"
    }
    return when {
        effectiveCode.startsWith("en") -> EnglishStrings
        effectiveCode.startsWith("es") -> SpanishStrings
        effectiveCode.startsWith("fr") -> FrenchStrings
        else -> GermanStrings
    }
}

val LocalAppStrings = staticCompositionLocalOf { GermanStrings }
